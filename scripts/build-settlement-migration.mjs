#!/usr/bin/env node
/** Reproducible offline assembly. Never connects to a database or runs SQL. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const sources=[
 'settlement-preflight.sql','settlement-ledger.sql','settlement-runtime.sql','settlement-release-policy.sql','settlement-checkout-cutover.sql',
 'settlement-recovery.sql','settlement-outflows.sql','settlement-observability.sql',
 'settlement-watchdog.sql','settlement-external.sql','settlement-legacy-ownership.sql','settlement-funding.sql',
 'settlement-guest-recovery.sql','settlement-replacement.sql','settlement-replacement-cleanup.sql','settlement-fulfillment.sql',
];
const prefix=path.join(root,'docs/payments/drafts');
const read=name=>fs.readFileSync(path.join(prefix,name),'utf8');
function replaceOnce(sql,from,to){
 if(sql.split(from).length!==2)throw Error('Settlement adoption anchor changed: '+from);
 return sql.replace(from,()=>to);
}
function between(sql,start,end){
 const from=sql.indexOf(start),to=sql.indexOf(end);
 if(from<0||to<=from||sql.indexOf(start,from+1)!==-1||sql.indexOf(end,to+1)!==-1)
  throw Error('Settlement adoption section changed: '+start);
 return sql.slice(from,to).trim();
}
function body(sql,name){
 sql=sql.trim().replace(/^BEGIN;\s*$/m,'').replace(/^COMMIT;\s*$/m,'');
 if(!sql.trim()||/^\s*(?:BEGIN|COMMIT);/m.test(sql))throw Error('Invalid SQL fragment: '+name);
 return sql;
}
function assemble(adopt){
 let output='-- GENERATED by node scripts/build-settlement-migration.mjs. Do not edit.\n';
 output+=adopt?'-- Receipt-safe adoption candidate. Offline until reviewed. No schedules or activation.\nBEGIN;\n':'-- Offline draft only. All execution gates remain OFF; no policies or schedules are enabled.\nBEGIN;\n';
 const append=(name,sql=read(name))=>{output+='\n-- SOURCE: docs/payments/drafts/'+name+'\n'+body(sql,name)+'\n';};
 if(adopt)append('settlement-adoption-preflight.sql');
 for(const name of sources){
  let sql=read(name);
  if(adopt&&name==='settlement-preflight.sql'){
   sql=replaceOnce(sql,` IF to_regnamespace('dvnt_settlement') IS NOT NULL THEN
  RAISE EXCEPTION 'existing settlement namespace requires reviewed adoption; offline artifact cannot be applied';
 END IF;
`,'');
  }
  if(adopt&&name==='settlement-runtime.sql'){
   const start='CREATE FUNCTION public.settlement_legacy_event_eligible(';
   const beforeSummary=between(sql,start,'CREATE FUNCTION public.settlement_actor_summary(');
   const terminal=beforeSummary.indexOf('$$;');
   if(terminal<0)throw Error('Legacy settlement function terminator missing');
   sql=replaceOnce(sql,beforeSummary.slice(0,terminal+3),'');
   sql=replaceOnce(sql,' IF e.status IN (',` IF dvnt_settlement.adopted_event_is_fenced(e.id) THEN
  RAISE EXCEPTION 'existing receipt or legacy claim requires manual reconciliation'; END IF;
 IF e.status IN (`);
   sql=replaceOnce(sql,"  IF host IS NULL THEN RAISE EXCEPTION 'organizer identity missing'; END IF;",`  IF dvnt_settlement.adopted_event_is_fenced((v->>'event_id')::int) THEN
   RAISE EXCEPTION 'existing receipt or legacy claim requires manual reconciliation'; END IF;
  IF host IS NULL THEN RAISE EXCEPTION 'organizer identity missing'; END IF;`);
  }
  if(adopt&&name==='settlement-external.sql'){
   // Only operations that refer to new runtime tables carry over. The
   // deployed legacy receipt/reporting/session functions remain authoritative.
   const parts=[
    between(sql,'CREATE FUNCTION dvnt_settlement.guard_external_delivery()', '-- The settlement stamp'),
    between(sql,'CREATE OR REPLACE FUNCTION dvnt_settlement.promoter_obligation_satisfied(', 'CREATE OR REPLACE FUNCTION public.settlement_legacy_event_eligible('),
    between(sql,'CREATE OR REPLACE FUNCTION public.settlement_actor_summary(', '-- Append-only recovery provenance.'),
   ];
   sql=parts.join('\n\n');
  }
  append(name,sql);
  if(adopt&&name==='settlement-external.sql')append('settlement-adoption-interlocks.sql');
 }
 return output+"\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n";
}
for(const [filename,adopt] of [['settlement-runtime-v1.generated.sql',false],['settlement-adoption.generated.sql',true]]){
 const target=path.join(prefix,filename),output=assemble(adopt);
 if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8')!==output)throw Error('Generated settlement SQL is stale: '+filename);
  console.log(filename+' matches ordered sources.');
 }else{fs.writeFileSync(target,output);console.log('Wrote '+path.relative(root,target));}
}
