#!/usr/bin/env node
/** Reproducible offline assembly. Never connects to a database or runs SQL. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const sources=[
 'settlement-preflight.sql','settlement-ledger.sql','settlement-runtime.sql','settlement-release-policy.sql',
 'settlement-recovery.sql','settlement-outflows.sql','settlement-observability.sql',
 'settlement-watchdog.sql','settlement-external.sql','settlement-legacy-ownership.sql','settlement-funding.sql',
];
const target=path.join(root,'apps/mobile/supabase/migrations/20261111040111_settlement_runtime_v1.sql');
let output='-- GENERATED by node scripts/build-settlement-migration.mjs. Do not edit.\n-- Offline draft only. All execution gates remain OFF; no policies or schedules are enabled.\nBEGIN;\n';
for(const name of sources){
 const file=path.join(root,'docs/payments/drafts',name);
 let sql=fs.readFileSync(file,'utf8').trim();
 if(!sql)throw Error('Empty migration source: '+name);
 sql=sql.replace(/^BEGIN;\s*$/m,'').replace(/^COMMIT;\s*$/m,'');
 if(/^\s*(?:BEGIN|COMMIT);/m.test(sql))throw Error('Unexpected transaction boundary: '+name);
 output+='\n-- SOURCE: docs/payments/drafts/'+name+'\n'+sql+'\n';
}
output+='\nNOTIFY pgrst, \'reload schema\';\nCOMMIT;\n';
if(process.argv.includes('--check')){
 if(fs.readFileSync(target,'utf8')!==output)throw Error('Generated settlement migration is stale. Run the assembler.');
 console.log('Settlement migration matches ordered sources.');
}else{fs.writeFileSync(target,output);console.log('Wrote '+path.relative(root,target));}
