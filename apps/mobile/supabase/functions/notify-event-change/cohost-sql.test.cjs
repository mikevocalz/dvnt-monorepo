// Real SQL in disposable in-memory PostgreSQL; no production access.
// NODE_PATH must include @electric-sql/pglite installed outside this repository.
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');
const migrations = path.resolve(__dirname, '../../migrations');
const read = file => fs.readFileSync(path.join(migrations, file), 'utf8');

test('accepted cohosts edit event content and catalog, never ownership or financial controls', { timeout: 120000 }, async t => {
  const db = new PGlite();
  const sql = async (text, args = []) => (await db.query(text, args)).rows;
  const login = async sub => {
    await db.exec('RESET ROLE');
    await sql("SELECT set_config('request.jwt.claims', $1, false)", [JSON.stringify({ sub, role: 'authenticated' })]);
    await db.exec('SET ROLE authenticated');
  };
  try {
    await db.exec(`
      CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS; CREATE ROLE anon;
      CREATE TABLE events (id integer PRIMARY KEY, host_id text, title text, description text,
        start_date timestamptz, end_date timestamptz, flyer_image_url text, video_flyer_url text,
        cover_image_url text, price integer, status text DEFAULT 'published', payout_account text,
        total_attendees integer DEFAULT 0, attendees integer DEFAULT 0, max_attendees integer, future_security_field text);
      CREATE TABLE event_co_organizers(id serial PRIMARY KEY,event_id integer,user_id text,accepted boolean,role text);
      CREATE TABLE ticket_types(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,event_id integer,
        name text, price_cents integer, quantity_total integer DEFAULT 100,
        quantity_sold integer DEFAULT 0,quantity_held integer DEFAULT 0,quantity_reserved_comp integer NOT NULL DEFAULT 0,capacity_alert_level integer NOT NULL DEFAULT 0);
      CREATE TABLE ticket_addons(id integer PRIMARY KEY,event_id integer,price_cents integer);
      CREATE TABLE ticket_addon_variants(id integer PRIMARY KEY,addon_id integer,price_cents integer);
      ALTER TABLE ticket_addons ENABLE ROW LEVEL SECURITY;
      ALTER TABLE ticket_addon_variants ENABLE ROW LEVEL SECURITY;
      CREATE POLICY addons_select ON ticket_addons FOR SELECT TO authenticated USING(true);
      CREATE POLICY variants_select ON ticket_addon_variants FOR SELECT TO authenticated USING(true);
      INSERT INTO ticket_addons VALUES(1,1,100);
      INSERT INTO ticket_addon_variants VALUES(1,1,100);
      ALTER TABLE event_co_organizers ENABLE ROW LEVEL SECURITY;
      CREATE POLICY staff_self ON event_co_organizers FOR SELECT TO authenticated
        USING(user_id=current_setting('request.jwt.claims',true)::json->>'sub');
      ALTER TABLE events ENABLE ROW LEVEL SECURITY;
      ALTER TABLE ticket_types ENABLE ROW LEVEL SECURITY;
      GRANT SELECT,UPDATE,DELETE ON events TO authenticated;
      GRANT SELECT ON event_co_organizers TO authenticated;
      GRANT SELECT,INSERT,UPDATE ON ticket_types TO authenticated;
      GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
      CREATE POLICY events_select ON events FOR SELECT TO authenticated USING(true);
      CREATE POLICY ticket_types_select ON ticket_types FOR SELECT TO authenticated USING(true);
      CREATE POLICY events_delete_host ON events FOR DELETE TO authenticated
        USING(host_id = current_setting('request.jwt.claims',true)::json->>'sub');
      INSERT INTO events(id,host_id,title,price) VALUES(1,'host','Before',100),(2,'other-host','Other',200);
      INSERT INTO event_co_organizers(event_id,user_id,accepted,role) VALUES
        (1,'editor',true,'editor'),(1,'admin',true,'admin'),(1,'scanner',true,'scanner'),
        (1,'pending',false,'editor'),(1,'null-acceptance',null,'admin'),(2,'editor',true,'editor');
      INSERT INTO ticket_types(event_id,name,price_cents) VALUES(1,'GA',100),(2,'Other',200);
      CREATE FUNCTION maintain_counters() RETURNS void LANGUAGE sql SECURITY DEFINER AS
        $$ UPDATE public.events SET total_attendees=total_attendees+1 WHERE id=1;
           UPDATE public.ticket_types SET quantity_sold=quantity_sold+1 WHERE id=1; $$;
      GRANT EXECUTE ON FUNCTION maintain_counters() TO authenticated;
    `);
    await db.exec(read('20260614211611_enforce_event_owner_write_trigger.sql'));
    await db.exec(read('20260613153305_capacity_below_sold_guards.sql'));
    await db.exec(read('20260806400000_ticket_addons_host_write_policies.sql'));
    await db.exec(read('20261111120000_accepted_cohost_event_editing.sql'));
    await db.exec(read('20261111120000_accepted_cohost_event_editing.sql'));
    for (const actor of ['host', 'editor', 'admin']) await t.test(`${actor} saves content, flyer, dates and tier price`, async () => {
      await login(actor);
      assert.equal((await sql("UPDATE events SET title=$1,flyer_image_url='https://test/flyer.jpg',start_date='2027-01-01',end_date='2027-01-02',price=500 WHERE id=1 RETURNING id", [actor])).length, 1);
      assert.equal((await sql('UPDATE ticket_types SET price_cents=500 WHERE id=1 RETURNING id')).length, 1);
      for (const table of ['ticket_addons', 'ticket_addon_variants']) {
        assert.equal((await sql(`UPDATE ${table} SET price_cents=500 WHERE id=1 RETURNING id`)).length, 1);
      }
      assert.equal((await sql("INSERT INTO ticket_types(event_id,name,price_cents) VALUES(1,'New',700) RETURNING id")).length, 1);
    });
    for (const actor of ['scanner', 'pending', 'null-acceptance', 'removed', 'unrelated']) await t.test(`${actor} cannot edit even with direct REST-equivalent writes`, async () => {
      await login(actor);
      assert.equal((await sql("UPDATE events SET title='bad' WHERE id=1 RETURNING id")).length, 0);
      assert.equal((await sql('UPDATE ticket_types SET price_cents=1 WHERE id=1 RETURNING id')).length, 0);
      await assert.rejects(sql("INSERT INTO ticket_types(event_id,name,price_cents) VALUES(1,'bad',1)"), /row-level security/);
      assert.equal((await sql('DELETE FROM events WHERE id=1 RETURNING id')).length, 0);
      for (const table of ['ticket_addons', 'ticket_addon_variants']) {
        assert.equal((await sql(`UPDATE ${table} SET price_cents=1 WHERE id=1 RETURNING id`)).length, 0);
      }
    });
    for (const actor of ['editor', 'admin']) await t.test(`${actor} cannot change protected fields or event ownership`, async () => {
      await login(actor);
      for (const patch of ["host_id='editor'", "payout_account='bad'", "status='cancelled'", "future_security_field='bad'", 'total_attendees=999', 'attendees=999', 'id=99']) {
        await assert.rejects(sql(`UPDATE events SET ${patch} WHERE id=1`), /not authorized/);
      }
      for (const patch of ['quantity_sold=999','quantity_held=999','quantity_reserved_comp=999','capacity_alert_level=2','event_id=2','id=99']) {
        await assert.rejects(sql(`UPDATE ticket_types SET ${patch} WHERE id=1`), /Only ticket catalog/);
      }
      for (const counter of ['quantity_sold','quantity_held','quantity_reserved_comp','capacity_alert_level']) {
        await assert.rejects(sql(`INSERT INTO ticket_types(event_id,name,${counter}) VALUES(1,'bad',999)`), /server-managed/);
      }
      assert.equal((await sql('DELETE FROM events WHERE id=1 RETURNING id')).length, 0);
    });
    await t.test('missing subject and anonymous clients cannot edit events', async () => {
      await login(null);
      assert.equal((await sql("UPDATE events SET title='bad' WHERE id=1 RETURNING id")).length, 0);
      await db.exec('RESET ROLE; SET ROLE anon');
      await assert.rejects(sql("UPDATE events SET title='bad' WHERE id=1"), /permission denied/);
    });
    await t.test('revoked permission takes effect on the next save', async () => {
      await db.exec('RESET ROLE'); await sql("DELETE FROM event_co_organizers WHERE user_id='editor'");
      await login('editor');
      assert.equal((await sql("UPDATE events SET title='bad' WHERE id=1 RETURNING id")).length, 0);
      assert.equal((await sql('UPDATE ticket_types SET price_cents=1 WHERE id=1 RETURNING id')).length, 0);
    });
    await t.test('trusted counter maintenance still works under a buyer JWT', async () => {
      await login('unrelated'); await sql('SELECT maintain_counters()');
      assert.equal((await sql('SELECT total_attendees FROM events WHERE id=1'))[0].total_attendees, 1);
      assert.equal((await sql('SELECT quantity_sold FROM ticket_types WHERE id=1'))[0].quantity_sold, 1);
    });
    await t.test('existing capacity-below-sold protections remain active for cohosts', async () => {
      await login('admin');
      await assert.rejects(sql('UPDATE ticket_types SET quantity_total=0 WHERE id=1'), /capacity_below_sold/);
      await assert.rejects(sql('UPDATE events SET max_attendees=0 WHERE id=1'), /capacity_below_sold/);
    });
    await t.test('owner retains financial settings; unrelated event remains protected', async () => {
      await login('host');
      assert.equal((await sql("UPDATE events SET payout_account='owner-account' WHERE id=1 RETURNING id")).length, 1);
      assert.equal((await sql("UPDATE events SET title='bad' WHERE id=2 RETURNING id")).length, 0);
    });
  } finally { await db.close(); }
});

test('tier guard works against historical UUID schema and real v2 counter defaults', { timeout: 120000 }, async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      CREATE ROLE authenticated; CREATE ROLE service_role; CREATE ROLE anon;
      CREATE TABLE events(id integer PRIMARY KEY,host_id text);
      CREATE TABLE event_co_organizers(event_id integer,user_id text,accepted boolean,role text);
      INSERT INTO events VALUES(1,'host');
      INSERT INTO event_co_organizers VALUES(1,'editor',true,'editor');
      GRANT SELECT ON events,event_co_organizers TO authenticated;
    `);
    // Use the actual schema, not the lightweight integer-ID matrix fixture.
    const base = read('20260301_events_ticketing_v2.sql').match(/CREATE TABLE IF NOT EXISTS ticket_types \([\s\S]*?\n\);/)[0];
    await db.exec(base);
    const legacyColumns = read('20260413100001_fix_event_detail_comments_table.sql')
      .split('\n').filter(line => line.startsWith('ALTER TABLE ticket_types ADD COLUMN')).join('\n');
    await db.exec(legacyColumns);
    await db.exec(read('20260424_ticket_types_capacity_alert.sql'));
    await db.exec(read('20260613144937_ticket_tier_model_v2.sql'));
    await db.exec(read('20261111120000_accepted_cohost_event_editing.sql'));
    await db.exec(`
      ALTER TABLE ticket_types ENABLE ROW LEVEL SECURITY;
      CREATE POLICY ticket_types_select ON ticket_types FOR SELECT USING(true);
      GRANT SELECT,INSERT,UPDATE ON ticket_types TO authenticated;
      SELECT set_config('request.jwt.claims','{"sub":"editor","role":"authenticated"}',false);
      SET ROLE authenticated;
    `);
    const row = (await db.query("INSERT INTO ticket_types(event_id,name,price_cents) VALUES(1,'GA',500) RETURNING *")).rows[0];
    assert.match(row.id, /^[0-9a-f-]{36}$/);
    for (const field of ['quantity_sold', 'quantity_held', 'quantity_reserved_comp', 'capacity_alert_level']) assert.equal(row[field], 0);
    await db.query('UPDATE ticket_types SET price_cents=700 WHERE id=$1', [row.id]);
    await assert.rejects(db.query('UPDATE ticket_types SET quantity_reserved_comp=1 WHERE id=$1', [row.id]), /Only ticket catalog/);
    await assert.rejects(db.query("INSERT INTO ticket_types(event_id,name,capacity_alert_level) VALUES(1,'bad',100)"), /server-managed/);
  } finally { await db.close(); }
});
