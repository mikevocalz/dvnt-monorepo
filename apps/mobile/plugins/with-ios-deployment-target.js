/**
 * Expo Config Plugin: force every Pod target to the app's iOS deployment target.
 *
 * CocoaPods honours each podspec's own `deployment_target`, so a pod declaring
 * iOS 15.1 stays at 15.1 even when the Podfile platform is 17.0. That is fine
 * until such a target imports a module built for a HIGHER target — Swift then
 * refuses the import outright:
 *
 *   compiling for iOS 15.1, but module 'ExpoModulesCore' has a minimum
 *   deployment target of iOS 16.4
 *
 * which is what failed the first development build (a2bc68d8). After a plain
 * prebuild, 336 pod targets were still pinned at 15.1 against 170 at 16.4.
 *
 * This appends a post_install pass that raises anything BELOW the configured
 * target up to it, and never lowers a pod that legitimately wants more. It must
 * be a plugin rather than a Podfile edit: `ios/` is regenerated by prebuild, and
 * .easignore strips it from the upload so EAS always regenerates it too.
 */

const { withDangerousMod } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

const MARKER = "# dvnt: enforce minimum iOS deployment target";

function buildSnippet(target) {
  return `
    ${MARKER}
    installer.pods_project.targets.each do |t|
      t.build_configurations.each do |config|
        current = config.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        if current.nil? || current.to_f < ${target}.to_f
          config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '${target}'
        end
      end
    end
`;
}

module.exports = function withIosDeploymentTarget(config, { target } = {}) {
  const deploymentTarget =
    target || config.ios?.deploymentTarget || "17.0";

  return withDangerousMod(config, [
    "ios",
    (cfg) => {
      const podfile = path.join(
        cfg.modRequest.platformProjectRoot,
        "Podfile",
      );
      let contents = fs.readFileSync(podfile, "utf8");

      if (contents.includes(MARKER)) {
        return cfg;
      }

      // Insert at the top of the existing post_install block so it runs after
      // CocoaPods has created the targets but alongside the other hooks.
      const anchor = "post_install do |installer|";
      const idx = contents.indexOf(anchor);
      if (idx === -1) {
        throw new Error(
          "[with-ios-deployment-target] no post_install block found in the Podfile — " +
            "the generated Podfile shape changed; update this plugin.",
        );
      }

      const insertAt = idx + anchor.length;
      contents =
        contents.slice(0, insertAt) +
        buildSnippet(deploymentTarget) +
        contents.slice(insertAt);

      fs.writeFileSync(podfile, contents);
      return cfg;
    },
  ]);
};
